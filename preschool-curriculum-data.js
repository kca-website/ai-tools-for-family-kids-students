function getAllPreschoolSubunits() {
  return PRESCHOOL_CURRICULUM.fields.flatMap(field =>
    field.units.flatMap(unit =>
      unit.subunits.map(subunit => ({
        fieldId: field.id,
        field: field.title,
        unitId: unit.id,
        unit: unit.title,
        source: field.source,
        ...subunit
      }))
    )
  );
}

