import fs from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const gel = require('../gel-schoolbook-source-map-2026-2027.js');
const overrides = require('../gel-schoolbook-manual-overrides-2026-2027.js');
const phase25 = require('../gel-schoolbook-manual-overrides-phase25-2026-2027.js');
const general = require('../general-education-book-sections-2026-2027.js');

const manual = new Set(
  [...(overrides.entries || []), ...(phase25.entries || [])]
    .map((entry) => `${entry.subjectId}\n${entry.label}`)
);
const subjects = {};

function add(subjectId, label) {
  if (!subjectId || !label) return;
  if (!subjects[subjectId]) subjects[subjectId] = [];
  if (!subjects[subjectId].includes(label)) subjects[subjectId].push(label);
}

for (const subject of Object.values(gel.all())) {
  for (const topic of subject.topicMappings || []) {
    const key = `${subject.subjectId}\n${topic.label}`;
    const runtimeGrounded =
      (topic.status === 'exact-html' && topic.confidence === 'high') ||
      topic.status === 'exact-pdf' ||
      manual.has(key);
    if (runtimeGrounded) add(subject.subjectId, topic.label);
  }
}

for (const subjectId of general.ids || []) {
  if (!/-gymnasiou$|-lykeiou$/i.test(subjectId)) continue;
  const row = general.get(subjectId);
  // Every secondary section in this catalog is exercised by the live
  // /api/study-grounding-audit gate. The generated manifest is refreshed only
  // after that audit reports zero runtime failures.
  for (const label of row?.sections || []) add(subjectId, label);
}

for (const labels of Object.values(subjects)) labels.sort((a, b) => a.localeCompare(b, 'el'));
const ordered = Object.fromEntries(Object.entries(subjects).sort(([a], [b]) => a.localeCompare(b)));
const payload = JSON.stringify(ordered);
const output = `// AUTO-GENERATED by scripts/build-secondary-grounding-availability.mjs.\n` +
`// Only topics with an exact runtime-consumable official source are listed.\n` +
`(function(root){\n  "use strict";\n  const subjects=${payload};\n  const sets=new Map(Object.entries(subjects).map(([id,labels])=>[id,new Set(labels)]));\n  const api=Object.freeze({\n    schoolYear:"2026-2027",\n    subjects:Object.freeze(subjects),\n    has(subjectId,label){return sets.get(String(subjectId||""))?.has(String(label||"").trim())||false;}\n  });\n  if(root)root.AITOOLSKIDS_SECONDARY_GROUNDING_AVAILABILITY=api;\n  if(typeof module==="object"&&module.exports)module.exports=api;\n})(typeof window!=="undefined"?window:null);\n`;

fs.writeFileSync(new URL('../secondary-grounding-availability-2026-2027.js', import.meta.url), output);
console.log(`Wrote ${Object.keys(ordered).length} subjects / ${Object.values(ordered).reduce((n, labels) => n + labels.length, 0)} verified topics.`);
