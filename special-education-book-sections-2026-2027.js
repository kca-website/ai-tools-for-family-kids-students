  const fold = (s) => String(s || "").normalize("NFC").replace(/\s+/g, " ").trim();
  function get(subjectId, label) {
    const subject = SUBJECTS[String(subjectId || "")];
    if (!subject) return null;
    const unit = subject.units.find(([l]) => fold(l) === fold(label));
    return unit ? { book: subject.book, label: unit[0], pages: unit[1] } : null;
  }
  // Keep only the page body; for a subsection cut between its heading and the next one.
  // Returns "" (fail closed) when a heading is no longer where it was verified.
  function scopePageHtml(html, page) {
    const raw = String(html || "");
    if (!raw || !page) return "";
    const bodyTag = /<[^>]*id="eclass_ebook_body"[^>]*>/i.exec(raw);
    let from = bodyTag ? bodyTag.index + bodyTag[0].length : 0;
    let to = raw.length;
    // Markers are matched tolerantly to whitespace/line-ending differences in the served HTML.
    const find = (marker, fromIndex) => {
      const pattern = new RegExp(marker.trim().split(/\s+/).map((part) => part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("\\s+"), "g");
      pattern.lastIndex = fromIndex;
      const hit = pattern.exec(raw);
      return hit ? hit.index : -1;
    };
    if (page.start) {
      const at = find(page.start, from);
      if (at < 0) return "";
      from = at;
      if (page.end) {
        const end = find(page.end, at + 1);
        if (end < 0) return "";
        to = end;
      }
    }
    return `<html><body><div id="eclass_ebook_body">${raw.slice(from, to)}</div></body></html>`;
  }

