  const fold = (s) => String(s || "").toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "");

  function ageFor(zone, grade) {
    return (AGES[zone] || {})[grade] ?? null;
  }
  function allowed(id, age) {
    const t = TOOLS[id];
    if (!t) return false;
    if (age === null || age === undefined) return t.minAge <= 15; // unknown age: stay with tools open to 15-year-olds
    return t.minAge <= age;
  }
  function subjectTools(subject, label) {
    const text = fold(subject + " " + label);
    for (const [re, ids] of SUBJECT_RULES) if (re.test(text)) return ids;
    return [];
  }

  // → [{ id, name, url, desc, age, parent, reviewed }] — at most 3 (2 for special education).
  function pick({ action, zone, grade, subject = "", subjectLabel = "", lang = "el" } = {}) {
    const age = ageFor(zone, grade);
    const special = zone === "special";
    const max = special ? 2 : 3;
    const actionIds = (ACTIONS[action] || FALLBACK).filter((id) => allowed(id, age));
    const order = [];
    if (special && allowed("immersive-reader", age)) order.push("immersive-reader");
    order.push(...actionIds.slice(0, 2));
    order.push(...subjectTools(subject, subjectLabel).filter((id) => allowed(id, age)).slice(0, 1));
    order.push(...actionIds.slice(2));
    const ids = [...new Set(order)].slice(0, max);
    return ids.map((id) => {
      const t = TOOLS[id];
      return { id, name: t.name, url: t.url, desc: lang === "en" ? t.en : t.el, age: t.minAge, parent: t.parentAccountRequired, reviewed: t.reviewed };
    });
  }

