import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const { generateChat, getAiStatus } = createRequire(import.meta.url)('../ai-provider-router.js');
process.env.CLOUDFLARE_LLM_ACCOUNT_ID = 'test';
process.env.CLOUDFLARE_LLM_AI_TOKEN = 'test';
process.env.GROQ_API_KEY = 'test';
process.env.GEMINI_API_KEY = 'test-secret';
delete process.env.AI_PROVIDER_ORDER;
assert.deepEqual(getAiStatus().providers.map(p => p.name), ['cloudflare', 'groq', 'gemini']);
let calls = [];
let finishReason = 'STOP';
globalThis.fetch = async (url, options) => {
  calls.push(url);
  if (!url.includes('googleapis')) return new Response('{}', { status: 429 });
  const body = JSON.parse(options.body);
  assert.equal(options.headers['x-goog-api-key'], 'test-secret');
  assert.ok(!url.includes('test-secret'));
  assert.equal(body.systemInstruction.parts[0].text, 'School source rules');
  assert.deepEqual(body.contents.map(c => c.role), ['user', 'model', 'user']);
  assert.equal(body.generationConfig.thinkingConfig.thinkingBudget, 0);
  assert.equal(body.generationConfig.maxOutputTokens, 100);
  assert.equal(body.generationConfig.responseMimeType, 'application/json');
  return Response.json({ candidates: [{ finishReason, content: { parts: [{ thought: true, text: 'hidden' }, { text: '{"answer":"4"}' }] } }], usageMetadata: { promptTokenCount: 20, candidatesTokenCount: 5, totalTokenCount: 25 } });
};
const request = { messages: [{ role: 'system', content: 'School source rules' }, { role: 'user', content: '2+2?' }, { role: 'assistant', content: 'Try adding.' }, { role: 'user', content: '4?' }], maxTokens: 100, responseFormat: { type: 'json_object' } };
const result = await generateChat(request);
assert.equal(result.provider, 'gemini');
assert.equal(result.ok, true);
assert.equal(result.model, 'gemini-2.5-flash-lite');
assert.equal(result.text, '{"answer":"4"}');
assert.equal(result.usage.totalTokens, 25);
assert.equal(calls.length, 3);
finishReason = 'SAFETY';
assert.equal((await generateChat(request)).status, 422);
finishReason = 'MAX_TOKENS';
assert.equal((await generateChat(request)).ok, false);
delete process.env.GEMINI_API_KEY;
assert.deepEqual(getAiStatus().providers.map(p => p.name), ['cloudflare', 'groq']);
console.log('Gemini fallback tests passed');
