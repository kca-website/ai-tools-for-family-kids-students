import { pickFinder } from './lib/home-finder.mjs';
import {chromium} from 'playwright';
import axe from 'axe-core';
import assert from 'node:assert/strict';
import {mkdirSync, writeFileSync} from 'node:fs';

const browser=await chromium.launch({headless:true});
const base='http://127.0.0.1:4173';
const report=[];
mkdirSync('docs/ux-evidence',{recursive:true});
try {
  for(const width of [320,375,390,768,1280]) {
    const page=await browser.newPage({viewport:{width,height:900},reducedMotion:'reduce'});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(base,{waitUntil:'domcontentloaded'});
    await page.waitForSelector('#homeV9Finder [data-finder-need]');
    await page.waitForFunction(()=>window.__aitools4kidsHeavyLoaded);
    await page.waitForLoadState('networkidle');
    assert.ok(await page.locator('#homeV9AllTools').isVisible(), 'All AI tools remain discoverable');
    assert.ok(await page.locator('#homeV11Paths a[href="/special-education.html"]').isVisible(), 'Special Education remains discoverable');
    assert.ok(await page.locator('#homeV8Eng a').isVisible(), 'GSL remains discoverable');
    assert.ok(await page.locator('#homeV11Paths a[href="/higher-education-pilot.html"]').isVisible(), 'University pilot remains discoverable');
    await pickFinder(page,{need:'stuck',zone:'primary'});
    assert.equal(await page.locator('#homeV9FinderCta').getAttribute('href'),'/primary/guardian/tutor');
    assert.equal(await page.locator('#homeV9Finder [data-finder-role]').count(),0,'Primary help always opens the adult pathway, so no role question');
    await pickFinder(page,{need:'study',zone:'middle'});
    await page.locator('#homeV11PdfLink').click();
    await page.waitForSelector('#studyNotes');
    await page.waitForFunction(()=>window.AITOOLSKIDS_LEARNING_ACTIONS);
    assert.equal(await page.locator('#zone').inputValue(),'middle','Study retains selected level');
    assert.equal(await page.locator('#chromeContext .ia-related [aria-current="page"]').getAttribute('data-ia-key'),'study','Related-task bar marks AI Study as current');
    assert.match(await page.locator('#chromeContext .ia-related__level').innerText(),/Γυμνάσιο/,'Level context is carried into AI Study');
    assert.equal(await page.locator('#chromeContext .ia-related a[data-ia-key="practice"]').getAttribute('href'),'/middle/guardian/quiz','Practice keeps the level without asking again');
    await page.locator('#notesPaste').fill('Το νερό έχει τρεις φυσικές καταστάσεις: στερεή, υγρή και αέρια.');
    await page.locator('#usePastedNotes').click();
    assert.ok(await page.locator('#sourceModeNotice').isVisible(),'Source mode is activated by real notes');
    await page.goBack();await page.waitForSelector('#homeV9FinderCta');
    assert.equal(await page.locator('#homeV9Finder [data-finder-need="study"]').getAttribute('aria-pressed'),'true','Back restores the chosen task');
    assert.equal(await page.locator('#homeV9Finder [data-finder-zone="middle"]').getAttribute('aria-pressed'),'true','Back restores the chosen level');
    await pickFinder(page,{need:'stuck',zone:'epal'});
    assert.equal(await page.locator('#homeV9FinderCta').getAttribute('href'),'/high/student/tutor?schoolType=epal');
    await pickFinder(page,{need:'study'});await page.locator('#homeV9FinderCta').click();
    await page.waitForFunction(()=>window.AITOOLSKIDS_LEARNING_ACTIONS);
    assert.equal(await page.locator('#zone').inputValue(),'high');
    assert.equal(await page.locator('#schoolType').inputValue(),'epal','Study preselects EPAL rather than GEL');
    await page.goBack();await page.waitForSelector('#homeV9FinderCta');
    await pickFinder(page,{need:'practice',zone:'epal'});
    assert.ok(await page.locator('.home-v9-finder__extra[href*="mode=practice"]').isVisible(),'Known-unit practice remains directly available');
    await page.locator('#homeV9FinderCta').click();
    await page.waitForSelector('#epalPracticeMapModal');
    assert.ok(await page.locator('#epalPracticeMapModal').isVisible(),'EPAL practice opens diagnostic, not the default GEL route');
    await page.locator('.epmap__close').click();
    await pickFinder(page,{need:'organize'});
    assert.equal(await page.locator('#homeV9FinderCta').getAttribute('href'),'/organosi-meletis-ai.html');
    await pickFinder(page,{need:'study',zone:'high'});await page.locator('#homeV9FinderCta').click();await page.waitForSelector('#zone');await page.waitForFunction(()=>window.AITOOLSKIDS_LEARNING_ACTIONS);
    assert.equal(await page.locator('#zone').inputValue(),'high');
    await page.goBack();await page.waitForSelector('#homeV9FinderCta');
    await pickFinder(page,{need:'teacher'});assert.equal(await page.locator('#homeV9FinderCta').getAttribute('href'),'/teacher-assistant.html');
    await pickFinder(page,{need:'practice',zone:'special'});
    assert.ok(await page.locator('#homeV9FinderCta[data-special-education-diagnostic]').count());
    await page.locator('#siteMenuToggle').click();
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#siteMenuToggle').getAttribute('aria-expanded'),'false');
    assert.equal(await page.locator('#siteMenuToggle').evaluate(el=>el===document.activeElement),true);
    await page.locator('#langEn').click();await page.waitForFunction(()=>document.documentElement.lang==='en');
    assert.match(await page.locator('#homeV9AllTools').innerText(),/AI tools/);
    assert.match(await page.locator('#homeV8FinderTitle').innerText(),/What do you want to do today/);
    await page.locator('#langEl').click();await page.waitForFunction(()=>document.documentElement.lang==='el');
    await page.waitForFunction(()=>document.querySelector('#homeV8FinderTitle')?.textContent.includes('Τι θέλεις'));
    await pickFinder(page,{need:'stuck',zone:'middle'});
    assert.ok(await page.locator('#homeV11Step .home-v11-step__explain').isVisible(),'Each task explains itself before you leave the homepage');
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth);
    assert.ok(overflow<=1,`${width}: horizontal overflow ${overflow}`);
    // Language changes rebuild the homepage asynchronously. Measure the
    // controls after the Greek content and visible layout have both returned.
    await page.waitForFunction(()=>{const role=document.querySelector('#homeV9Finder [data-finder-role="guardian"]');return role?.textContent.includes('Γονιός') && [...document.querySelectorAll('#homeV9Finder button')].every(el=>el.getBoundingClientRect().height>0);});
    const navTargets=await page.locator('#chromeHeader a, #chromeHeader button, header.site-header a, header.site-header button').evaluateAll(els=>els.filter(el=>el.getBoundingClientRect().width>0).map(el=>({h:el.getBoundingClientRect().height,w:el.getBoundingClientRect().width,t:el.textContent.trim().slice(0,20)})));
    assert.ok(navTargets.every(t=>t.h>=24&&t.w>=24),`${width}: header targets below WCAG 2.2 minimum ${JSON.stringify(navTargets.filter(t=>t.h<24||t.w<24))}`);
    const targets=await page.locator('#homeV9Finder button').evaluateAll(els=>els.map(el=>({height:el.getBoundingClientRect().height,text:el.textContent})));
    assert.ok(targets.every(t=>t.height>=44),`${width}: touch targets ${JSON.stringify(targets.filter(t=>t.height<44))}`);
    await page.addScriptTag({content:axe.source});
    const scan=await page.evaluate(async()=>{const r=await axe.run({runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa','wcag22aa']}});return r.violations.map(v=>({id:v.id,impact:v.impact,targets:v.nodes.map(n=>n.target)}));});
    assert.deepEqual(scan,[],`${width}: accessibility violations: ${JSON.stringify(scan)}`);
    assert.deepEqual(errors,[],`${width}: runtime errors`);
    report.push({width,overflow,touchTargets:targets.length,axeViolations:scan.length,runtimeErrors:errors.length});
    if(width===390||width===1280){await pickFinder(page,{need:'study',zone:'middle'});await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:`docs/ux-evidence/home-${width}.png`,fullPage:true});}
    await page.close();
  }
  writeFileSync('docs/ux-evidence/checks.json',JSON.stringify(report,null,2)+'\n');
  console.log('Intent-first journeys, PDF notes, EPAL diagnostic, language, focus, touch targets and axe checks passed at 5 viewport widths.');
}finally{await browser.close();}
